`timescale 1ns / 1ps
//////////////////////////////////////////////////////////////////////////////////
// Курсовий проєкт, тема 5: Метроном
//
// Модуль: axi_metronome_broken
//
// ЗЛАМАНА КОПІЯ модуля axi_metronome для кроку 3 завдання.
// Навмисна помилка одна: період зберігається без віднімання одиниці, тому кожен
// проміжок між імпульсами на один такт довший, ніж потрібно (501 замість 500).
// Місце помилки позначене в коді словом "ОШИБКА". Решта коду збігається з оригіналом.
// У IP цей файл не входить.
// Призначення: формує імпульси tick із темпом, заданим в ударах на хвилину (BPM).
//              Керування лише через три регістри AXI4-Lite.
//
// Регістри (усі 32-бітні, незначущі розряди читаються нулями):
//   0x00  BPM     запис/читання  темп, 30..240; значення поза діапазоном
//                                обмежується найближчою межею ще під час запису
//   0x04  ENABLE  запис/читання  розряд [0]: 1 метроном працює, 0 стоїть
//   0x08  TICKS   читання        кількість імпульсів від моменту ввімкнення
//
// Період у тактах: CLK_HZ * 60 / BPM, заокруглення вниз.
// Зміна темпу діє з початку наступного проміжку (після найближчого tick).
//
// Обмеження: період має бути довшим за час ділення (DIV_W + 1 такт),
//            тобто CLK_HZ не менше ніж приблизно 160.
//////////////////////////////////////////////////////////////////////////////////

module axi_metronome_broken #(
    parameter CLK_HZ = 1000                 // частота aclk в герцах (1000 для симуляции)
)(
    // ---------------- Такт и сброс ----------------
    input  wire        aclk,                // тактовый сигнал шины и логики
    input  wire        aresetn,             // асинхронный сброс, активный ноль

    // ---------------- AXI4-Lite: канал адреса записи ----------------
    input  wire [3:0]  s_axi_awaddr,        // адрес записи (смещение регистра)
    input  wire        s_axi_awvalid,       // мастер выставил адрес записи
    output wire        s_axi_awready,       // модуль принял адрес записи

    // ---------------- AXI4-Lite: канал данных записи ----------------
    input  wire [31:0] s_axi_wdata,         // записываемые данные
    input  wire [3:0]  s_axi_wstrb,         // стробы байтов (не используются, пишем слово целиком)
    input  wire        s_axi_wvalid,        // мастер выставил данные
    output wire        s_axi_wready,        // модуль принял данные

    // ---------------- AXI4-Lite: канал ответа на запись ----------------
    output wire [1:0]  s_axi_bresp,         // код ответа, всегда OKAY
    output reg         s_axi_bvalid,        // ответ на запись готов
    input  wire        s_axi_bready,        // мастер принял ответ

    // ---------------- AXI4-Lite: канал адреса чтения ----------------
    input  wire [3:0]  s_axi_araddr,        // адрес чтения (смещение регистра)
    input  wire        s_axi_arvalid,       // мастер выставил адрес чтения
    output wire        s_axi_arready,       // модуль принял адрес чтения

    // ---------------- AXI4-Lite: канал данных чтения ----------------
    output reg  [31:0] s_axi_rdata,         // прочитанные данные
    output wire [1:0]  s_axi_rresp,         // код ответа, всегда OKAY
    output reg         s_axi_rvalid,        // данные чтения готовы
    input  wire        s_axi_rready,        // мастер принял данные

    // ---------------- Выход метронома ----------------
    output reg         tick                 // импульс длительностью ровно один такт aclk
);

    // ---------------- Константы ----------------
    localparam BPM_MIN = 8'd30;             // нижняя граница темпа
    localparam BPM_MAX = 8'd240;            // верхняя граница темпа
    localparam BPM_RST = 8'd120;            // темп после сброса
    localparam DIV_W   = 36;                // разрядность делимого, периода и счётчика тактов

    localparam [DIV_W-1:0] TICKS_PER_MIN = 36'd60 * CLK_HZ; // тактов aclk в одной минуте

    // ---------------- Регистры, видимые процессору ----------------
    reg  [7:0]  bpm_reg;                    // BPM, уже ограниченный диапазоном 30..240
    reg         enable_reg;                 // ENABLE, разряд [0]
    reg  [31:0] ticks_reg;                  // TICKS, счётчик выданных импульсов

    // ============================================================================
    // AXI4-Lite: запись
    // ============================================================================

    // Адрес и данные принимаются одновременно, когда оба выставлены и нет неотданного ответа
    wire wr_en = s_axi_awvalid & s_axi_wvalid & ~s_axi_bvalid;

    assign s_axi_awready = wr_en;           // готовность адреса только вместе с данными
    assign s_axi_wready  = wr_en;           // готовность данных только вместе с адресом
    assign s_axi_bresp   = 2'b00;           // OKAY

    // Ограничение записываемого темпа: сравнивается всё 32-битное слово.
    // Объявление и assign разделены: иначе упаковщик IP принимает bpm_clamped за порт (IP_Flow 19-587)
    wire [7:0] bpm_clamped;
    assign bpm_clamped = (s_axi_wdata < BPM_MIN) ? BPM_MIN :          // меньше 30 (в том числе 0) -> 30
                         (s_axi_wdata > BPM_MAX) ? BPM_MAX :          // больше 240 -> 240
                                                   s_axi_wdata[7:0];  // в диапазоне -> как есть

    always @(posedge aclk or negedge aresetn) begin
        if (!aresetn) begin
            bpm_reg      <= BPM_RST;        // после сброса темп 120
            enable_reg   <= 1'b0;           // после сброса метроном стоит
            s_axi_bvalid <= 1'b0;           // ответа нет
        end else begin
            if (wr_en) begin
                case (s_axi_awaddr[3:2])    // младшие два разряда адреса не значимы
                    2'd0: bpm_reg    <= bpm_clamped;     // 0x00 BPM
                    2'd1: enable_reg <= s_axi_wdata[0];  // 0x04 ENABLE
                    default: ;                           // 0x08 TICKS и 0x0C: запись игнорируется
                endcase
                s_axi_bvalid <= 1'b1;       // выставляем ответ на запись
            end else if (s_axi_bready) begin
                s_axi_bvalid <= 1'b0;       // мастер забрал ответ
            end
        end
    end

    // ============================================================================
    // AXI4-Lite: чтение
    // ============================================================================

    // Адрес чтения принимается, когда предыдущие данные уже отданы
    wire rd_en = s_axi_arvalid & ~s_axi_rvalid;

    assign s_axi_arready = rd_en;           // готовность адреса чтения
    assign s_axi_rresp   = 2'b00;           // OKAY

    always @(posedge aclk or negedge aresetn) begin
        if (!aresetn) begin
            s_axi_rdata  <= 32'd0;          // данных нет
            s_axi_rvalid <= 1'b0;           // данные не готовы
        end else begin
            if (rd_en) begin
                case (s_axi_araddr[3:2])
                    2'd0:    s_axi_rdata <= {24'd0, bpm_reg};    // 0x00 BPM
                    2'd1:    s_axi_rdata <= {31'd0, enable_reg}; // 0x04 ENABLE
                    2'd2:    s_axi_rdata <= ticks_reg;           // 0x08 TICKS
                    default: s_axi_rdata <= 32'd0;               // 0x0C: не используется
                endcase
                s_axi_rvalid <= 1'b1;       // данные готовы
            end else if (s_axi_rready) begin
                s_axi_rvalid <= 1'b0;       // мастер забрал данные
            end
        end
    end

    // ============================================================================
    // Логика метронома
    // ============================================================================

    reg              enable_d;              // ENABLE, задержанный на такт (для поиска момента включения)
    reg  [DIV_W-1:0] cnt;                   // счётчик тактов внутри текущего промежутка
    reg  [DIV_W-1:0] last_cnt;              // период минус 1: значение cnt в последнем такте промежутка
    reg              period_valid;          // деление закончено, last_cnt действителен

    // Последовательный делитель TICKS_PER_MIN / BPM (деление "в столбик", один разряд за такт)
    reg              div_busy;              // деление идёт
    reg  [5:0]       div_bits;              // сколько разрядов осталось обработать
    reg  [7:0]       div_dvs;               // делитель: темп, зафиксированный на начало промежутка
    reg  [DIV_W-1:0] div_quo;               // сначала делимое, по мере сдвига заполняется частным
    reg  [8:0]       div_rem;               // текущий остаток

    wire start_run = enable_reg & ~enable_d;                        // первый такт после включения
    wire last      = enable_reg & period_valid & (cnt == last_cnt); // последний такт промежутка
    wire div_start = start_run | last;                              // начало нового промежутка

    wire [8:0]       rem_sh   = {div_rem[7:0], div_quo[DIV_W-1]};   // остаток со вдвинутым очередным разрядом делимого
    wire             rem_ge   = (rem_sh >= {1'b0, div_dvs});        // делитель помещается в остаток
    wire [8:0]       rem_next = rem_ge ? (rem_sh - {1'b0, div_dvs}) : rem_sh; // новый остаток
    wire [DIV_W-1:0] quo_next = {div_quo[DIV_W-2:0], rem_ge};       // очередной разряд частного

    always @(posedge aclk or negedge aresetn) begin
        if (!aresetn) begin
            enable_d     <= 1'b0;
            cnt          <= {DIV_W{1'b0}};
            last_cnt     <= {DIV_W{1'b0}};
            period_valid <= 1'b0;
            div_busy     <= 1'b0;
            div_bits     <= 6'd0;
            div_dvs      <= BPM_RST;
            div_quo      <= {DIV_W{1'b0}};
            div_rem      <= 9'd0;
            ticks_reg    <= 32'd0;
            tick         <= 1'b0;
        end else begin
            enable_d <= enable_reg;         // запоминаем ENABLE для поиска фронта
            tick     <= last;               // импульс ровно на один такт после последнего такта промежутка

            if (!enable_reg) begin
                // ---- Метроном выключен: счётчик держится в нуле, импульсов нет ----
                cnt          <= {DIV_W{1'b0}};
                period_valid <= 1'b0;       // при следующем включении период считается заново
                div_busy     <= 1'b0;       // незаконченное деление отбрасывается
                // ticks_reg сохраняется, чтобы программа могла прочитать его после остановки
            end else begin
                // ---- Счётчик тактов промежутка ----
                if (last) cnt <= {DIV_W{1'b0}};     // промежуток закончился, начинаем следующий
                else      cnt <= cnt + 1'b1;        // обычный такт

                // ---- Счётчик выданных импульсов ----
                if (start_run) ticks_reg <= 32'd0;              // включение: счёт импульсов с нуля
                else if (last) ticks_reg <= ticks_reg + 1'b1;   // выдан ещё один импульс

                // ---- Вычисление периода ----
                if (div_start) begin
                    // Начало промежутка: фиксируем текущий темп и запускаем деление
                    div_dvs      <= bpm_reg;        // новый BPM начинает действовать именно здесь
                    div_quo      <= TICKS_PER_MIN;  // делимое
                    div_rem      <= 9'd0;           // остаток обнулён
                    div_bits     <= DIV_W;          // обработать все разряды делимого
                    div_busy     <= 1'b1;
                    period_valid <= 1'b0;           // старый период больше не действителен
                end else if (div_busy) begin
                    // Один шаг деления: один разряд частного за такт
                    div_rem  <= rem_next;
                    div_quo  <= quo_next;
                    div_bits <= div_bits - 1'b1;
                    if (div_bits == 6'd1) begin     // обработан последний разряд
                        last_cnt     <= quo_next;        // ОШИБКА (намеренная): должно быть quo_next - 1'b1
                        period_valid <= 1'b1;
                        div_busy     <= 1'b0;
                    end
                end
            end
        end
    end

endmodule
